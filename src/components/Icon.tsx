export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size?: number;
  strokeWidth?: number;
}

export function Icon({ name, size = 16, strokeWidth }: IconProps) {
  const Component = ICONS[name];
  return (
    <Component
      className="icon"
      size={size}
      strokeWidth={strokeWidth ?? (size <= 14 ? 2 : 1.75)}
      style={{ flexShrink: 0 }}
      aria-hidden="true"
    />
  );
}
